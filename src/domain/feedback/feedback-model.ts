/**
 * User feedback domain model.
 *
 * Feedback comes in 6 flavours. Every feedback entity carries a
 * PII-redacted body — the redactor (`feedback-redactor.ts`) runs before
 * storage, so the persisted body never contains file URIs, attachment
 * paths, exact amounts, UPI IDs, email addresses, payment references, or
 * raw OCR text.
 *
 * For `bug_report` feedback, the redactor ALSO strips local-only
 * attachment references entirely — we never upload a local-only file to
 * the feedback backend, even with the path redacted, because the file
 * itself may contain receipt images or OCR text.
 */

// ---------------------------------------------------------------------------
// Feedback types (6)
// ---------------------------------------------------------------------------

export type FeedbackType =
  | 'general'
  | 'feature_request'
  | 'bug_report'
  | 'ocr_correction'
  | 'nps'
  | 'app_store_review';

export const FEEDBACK_TYPES: readonly FeedbackType[] = [
  'general',
  'feature_request',
  'bug_report',
  'ocr_correction',
  'nps',
  'app_store_review',
] as const;

// ---------------------------------------------------------------------------
// NPS scoring
// ---------------------------------------------------------------------------

export const NPS_MIN_SCORE = 0;
export const NPS_MAX_SCORE = 10;

export function isValidNpsScore(score: number): boolean {
  return (
    Number.isInteger(score) &&
    score >= NPS_MIN_SCORE &&
    score <= NPS_MAX_SCORE
  );
}

export type NpsCategory = 'detractor' | 'passive' | 'promoter';

export function npsCategory(score: number): NpsCategory {
  if (!isValidNpsScore(score)) {
    throw new Error(`Invalid NPS score: ${score}`);
  }
  if (score <= 6) return 'detractor';
  if (score <= 8) return 'passive';
  return 'promoter';
}

// ---------------------------------------------------------------------------
// Feedback entity
// ---------------------------------------------------------------------------

export interface Feedback {
  /** Stable identifier (UUID generated by the use case). */
  readonly id: string;
  /** Type of feedback. */
  readonly type: FeedbackType;
  /** PII-redacted body (free text, max 4000 chars after redaction). */
  readonly body: string;
  /** Optional NPS score (0-10) — only for `nps` type. */
  readonly npsScore?: number;
  /** Optional NPS category derived from `npsScore`. */
  readonly npsCategory?: NpsCategory;
  /** Optional OCR correction metadata — bucketed amounts only. */
  readonly ocrCorrection?: OcrCorrectionMeta;
  /** App version that produced the feedback. */
  readonly appVersion: string;
  /** Platform that produced the feedback. */
  readonly platform: 'ios' | 'android' | 'web';
  /** ISO date-time when the feedback was submitted. */
  readonly submittedAt: string;
  /**
   * Whether the user explicitly opted in to be contacted about this
   * feedback. If true, a contact email MAY be stored separately in the
   * identity system; the feedback body itself never contains it.
   */
  readonly contactOptIn: boolean;
}

export interface OcrCorrectionMeta {
  /** Bucketed field-level correction counts (no values). */
  readonly fieldCorrections: Readonly<Record<string, number>>;
  /** Aggregate count of accepted fields (no values). */
  readonly acceptedFieldCount: number;
  /** Aggregate count of corrected fields (no values). */
  readonly correctedFieldCount: number;
}

// ---------------------------------------------------------------------------
// Construction
// ---------------------------------------------------------------------------

export const FEEDBACK_BODY_MAX_LENGTH = 4000;

export interface FeedbackCreateInput {
  readonly id: string;
  readonly type: FeedbackType;
  /**
   * Body MUST already be PII-redacted by `redactFeedbackBody`. The use
   * case enforces this contract — raw bodies are never accepted.
   */
  readonly body: string;
  readonly npsScore?: number;
  readonly ocrCorrection?: OcrCorrectionMeta;
  readonly appVersion: string;
  readonly platform: 'ios' | 'android' | 'web';
  readonly submittedAt: string;
  readonly contactOptIn: boolean;
}

export function createFeedback(input: FeedbackCreateInput): Feedback {
  if (!FEEDBACK_TYPES.includes(input.type)) {
    throw new Error(`Unknown feedback type: ${input.type}`);
  }
  if (input.body.length > FEEDBACK_BODY_MAX_LENGTH) {
    throw new Error(
      `Feedback body too long: ${input.body.length} > ${FEEDBACK_BODY_MAX_LENGTH}`,
    );
  }
  if (input.type === 'nps') {
    if (input.npsScore === undefined) {
      throw new Error('NPS feedback requires a npsScore');
    }
    if (!isValidNpsScore(input.npsScore)) {
      throw new Error(`Invalid NPS score: ${input.npsScore}`);
    }
  } else if (input.npsScore !== undefined) {
    throw new Error(`Non-NPS feedback (${input.type}) must not carry a npsScore`);
  }
  if (input.appVersion.trim().length === 0) {
    throw new Error('Feedback appVersion must not be empty');
  }
  if (Number.isNaN(Date.parse(input.submittedAt))) {
    throw new Error('Feedback submittedAt must be a valid ISO date-time');
  }

  const out: Feedback = {
    id: input.id,
    type: input.type,
    body: input.body,
    appVersion: input.appVersion,
    platform: input.platform,
    submittedAt: input.submittedAt,
    contactOptIn: input.contactOptIn,
    ...(input.npsScore !== undefined
      ? { npsScore: input.npsScore, npsCategory: npsCategory(input.npsScore) }
      : {}),
    ...(input.ocrCorrection !== undefined ? { ocrCorrection: input.ocrCorrection } : {}),
  };
  return out;
}
