/**
 * Growth experiments domain model.
 *
 * CRITICAL CONTRACT:
 *   - Experiments target ONBOARDING, NOTIFICATIONS, and REMINDER TIMING only.
 *   - Experiments NEVER touch financial areas (see `experiment-safety-guard.ts`).
 *   - Variants override UI/UX flags only — never financial flags.
 *   - Experiments must NOT cause sync conflicts or alter split calculations.
 *
 * Variants are deliberately a small, fixed enum so the safety guard can
 * reason about every possible variant a user might be assigned to.
 */

// ---------------------------------------------------------------------------
// Variants
// ---------------------------------------------------------------------------

export type ExperimentVariant =
  | 'control'
  | 'treatment_a'
  | 'treatment_b'
  | 'treatment_c';

export const EXPERIMENT_VARIANTS: readonly ExperimentVariant[] = [
  'control',
  'treatment_a',
  'treatment_b',
  'treatment_c',
] as const;

export function isExperimentVariant(value: unknown): value is ExperimentVariant {
  return (
    typeof value === 'string' &&
    (EXPERIMENT_VARIANTS as readonly string[]).includes(value)
  );
}

// ---------------------------------------------------------------------------
// Experiment surface (what UI area the experiment targets)
// ---------------------------------------------------------------------------

/**
 * The user-facing surface an experiment targets. Surfaces are restricted
 * to UI/UX areas only — financial surfaces are deliberately omitted
 * (they are listed in `FinancialArea` and blocked by the safety guard).
 */
export type ExperimentSurface =
  | 'onboarding_flow'
  | 'notification_content'
  | 'notification_timing'
  | 'reminder_cadence'
  | 'home_dashboard_layout'
  | 'capture_entry_point'
  | 'group_join_prompt';

export const EXPERIMENT_SURFACES: readonly ExperimentSurface[] = [
  'onboarding_flow',
  'notification_content',
  'notification_timing',
  'reminder_cadence',
  'home_dashboard_layout',
  'capture_entry_point',
  'group_join_prompt',
] as const;

export function isExperimentSurface(value: unknown): value is ExperimentSurface {
  return (
    typeof value === 'string' &&
    (EXPERIMENT_SURFACES as readonly string[]).includes(value)
  );
}

// ---------------------------------------------------------------------------
// Lifecycle
// ---------------------------------------------------------------------------

export type ExperimentStatus =
  | 'draft'
  | 'running'
  | 'paused'
  | 'completed'
  | 'cancelled';

export const EXPERIMENT_STATUSES: readonly ExperimentStatus[] = [
  'draft',
  'running',
  'paused',
  'completed',
  'cancelled',
] as const;

export function isExperimentStatus(value: unknown): value is ExperimentStatus {
  return (
    typeof value === 'string' &&
    (EXPERIMENT_STATUSES as readonly string[]).includes(value)
  );
}

/**
 * Per-variant weight, in arbitrary integer units (e.g. parts-per-100).
 * The assignment engine normalises weights, so the absolute values do not
 * matter — only the ratios between variants do.
 *
 * Weights MUST be non-negative integers.
 */
export interface VariantWeight {
  readonly variant: ExperimentVariant;
  readonly weight: number;
}

// ---------------------------------------------------------------------------
// Per-variant metric counters (aggregated, anonymous)
// ---------------------------------------------------------------------------

export interface VariantMetrics {
  readonly variant: ExperimentVariant;
  /** Number of unique participants assigned to this variant. */
  readonly enrolledCount: number;
  /** Number of participants who reached the success criterion. */
  readonly successCount: number;
  /** Number of participants who reached the failure criterion. */
  readonly failureCount: number;
}

// ---------------------------------------------------------------------------
// Experiment entity
// ---------------------------------------------------------------------------

export interface Experiment {
  /** Stable identifier (UUID, generated by the use case). */
  readonly id: string;
  /** Human-readable name (no PII). */
  readonly name: string;
  /** Description of what the experiment tests. */
  readonly description: string;
  /** UI/UX surface the experiment targets. */
  readonly surface: ExperimentSurface;
  /** Current lifecycle status. */
  readonly status: ExperimentStatus;
  /**
   * Per-variant weights. At least one entry per active variant; absent
   * variants default to weight 0. Weights MUST be non-negative integers.
   */
  readonly variantWeights: readonly VariantWeight[];
  /**
   * Percentage of eligible traffic allocated to the experiment
   * (0..100). The remaining traffic is excluded from assignment entirely
   * (no variant recorded).
   */
  readonly trafficAllocationPercent: number;
  /**
   * Free-form list of UI/UX feature flags the experiment overrides.
   * Financial flags are NOT permitted here — the safety guard rejects
   * any experiment that lists financial flags.
   */
  readonly overriddenFlags: readonly string[];
  /** ISO date-time when the experiment starts (or is scheduled to start). */
  readonly startsAt: string;
  /** ISO date-time when the experiment ends (or ended). */
  readonly endsAt: string;
  /** Schema version for the experiment definition. */
  readonly version: number;
}

// ---------------------------------------------------------------------------
// Construction
// ---------------------------------------------------------------------------

export interface ExperimentCreateInput {
  readonly id: string;
  readonly name: string;
  readonly description: string;
  readonly surface: ExperimentSurface;
  readonly status?: ExperimentStatus;
  readonly variantWeights: readonly VariantWeight[];
  readonly trafficAllocationPercent: number;
  readonly overriddenFlags?: readonly string[];
  readonly startsAt: string;
  readonly endsAt: string;
  readonly version?: number;
}

export const MIN_TRAFFIC_ALLOCATION = 0;
export const MAX_TRAFFIC_ALLOCATION = 100;
export const DEFAULT_EXPERIMENT_VERSION = 1;

export function createExperiment(input: ExperimentCreateInput): Experiment {
  if (input.id.trim().length === 0) {
    throw new Error('Experiment id must not be empty');
  }
  if (input.name.trim().length === 0) {
    throw new Error('Experiment name must not be empty');
  }
  if (!isExperimentSurface(input.surface)) {
    throw new Error(`Unknown experiment surface: ${input.surface}`);
  }
  if (!isExperimentStatus(input.status ?? 'draft')) {
    throw new Error(`Unknown experiment status: ${input.status ?? 'draft'}`);
  }
  if (
    !Number.isInteger(input.trafficAllocationPercent) ||
    input.trafficAllocationPercent < MIN_TRAFFIC_ALLOCATION ||
    input.trafficAllocationPercent > MAX_TRAFFIC_ALLOCATION
  ) {
    throw new Error(
      `trafficAllocationPercent must be an integer in [0, 100], got ${input.trafficAllocationPercent}`,
    );
  }
  if (input.variantWeights.length === 0) {
    throw new Error('Experiment must define at least one variant weight');
  }
  for (const w of input.variantWeights) {
    if (!isExperimentVariant(w.variant)) {
      throw new Error(`Unknown variant: ${w.variant}`);
    }
    if (!Number.isInteger(w.weight) || w.weight < 0) {
      throw new Error(
        `Variant ${w.variant} weight must be a non-negative integer, got ${w.weight}`,
      );
    }
  }
  const totalWeight = input.variantWeights.reduce((sum, w) => sum + w.weight, 0);
  if (totalWeight <= 0) {
    throw new Error('Total variant weight must be > 0');
  }
  if (Number.isNaN(Date.parse(input.startsAt))) {
    throw new Error('startsAt must be a valid ISO date-time');
  }
  if (Number.isNaN(Date.parse(input.endsAt))) {
    throw new Error('endsAt must be a valid ISO date-time');
  }
  if (Date.parse(input.endsAt) < Date.parse(input.startsAt)) {
    throw new Error('endsAt must not precede startsAt');
  }

  const experiment: Experiment = {
    id: input.id,
    name: input.name,
    description: input.description,
    surface: input.surface,
    status: input.status ?? 'draft',
    variantWeights: input.variantWeights,
    trafficAllocationPercent: input.trafficAllocationPercent,
    overriddenFlags: input.overriddenFlags ?? [],
    startsAt: input.startsAt,
    endsAt: input.endsAt,
    version: input.version ?? DEFAULT_EXPERIMENT_VERSION,
  };
  return experiment;
}

// ---------------------------------------------------------------------------
// Lifecycle transitions
// ---------------------------------------------------------------------------

/**
 * Allowed status transitions. Any transition not in this map is rejected.
 *
 *   draft → running
 *   running → paused | completed | cancelled
 *   paused → running | cancelled
 *   completed → (terminal)
 *   cancelled → (terminal)
 */
const ALLOWED_TRANSITIONS: Readonly<Record<ExperimentStatus, readonly ExperimentStatus[]>> = Object.freeze({
  draft: ['running'],
  running: ['paused', 'completed', 'cancelled'],
  paused: ['running', 'cancelled'],
  completed: [],
  cancelled: [],
});

export function canTransition(from: ExperimentStatus, to: ExperimentStatus): boolean {
  const allowed = ALLOWED_TRANSITIONS[from];
  return allowed !== undefined && (allowed as readonly string[]).includes(to);
}

export function transitionExperiment(
  experiment: Experiment,
  to: ExperimentStatus,
): Experiment {
  if (!canTransition(experiment.status, to)) {
    throw new Error(
      `Illegal experiment transition: ${experiment.status} → ${to}`,
    );
  }
  return { ...experiment, status: to };
}

/**
 * Returns true when the experiment is currently active for assignment
 * (i.e. running and within its date window).
 */
export function isExperimentActive(
  experiment: Experiment,
  nowIso: string,
): boolean {
  if (experiment.status !== 'running') return false;
  const now = Date.parse(nowIso);
  if (!Number.isFinite(now)) return false;
  if (now < Date.parse(experiment.startsAt)) return false;
  if (now > Date.parse(experiment.endsAt)) return false;
  return true;
}
