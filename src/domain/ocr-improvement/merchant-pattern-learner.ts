/**
 * Merchant pattern learner.
 *
 * CRITICAL CONTRACT:
 *   - This module learns REGEX PATTERNS from AGGREGATED, ANONYMIZED
 *     correction data only.
 *   - It NEVER stores raw merchant names. Patterns are abstract templates
 *     (e.g. "matches a sequence of 2-4 uppercase letters followed by
 *     2-6 digits") that can be applied to future extractions.
 *   - Learning requires a MINIMUM of 10 corrections before producing a
 *     pattern. Below that threshold, the learner returns `null` to avoid
 *     overfitting to noise.
 *   - Pure functions — no I/O, no globals, no mutation of inputs.
 *
 * The learner is fed by the `correction-statistics` module's output
 * (anonymized `CorrectionPatternCount` entries). It looks for repeated
 * patterns in the `extractedValuePattern` and `correctedValuePattern`
 * fields and produces a regex template that captures the shape.
 */

import type { CorrectionPatternCount } from './correction-statistics';

// ---------------------------------------------------------------------------
// Minimum sample threshold
// ---------------------------------------------------------------------------

export const MIN_CORRECTIONS_FOR_PATTERN = 10;

// ---------------------------------------------------------------------------
// Learned pattern
// ---------------------------------------------------------------------------

export interface LearnedMerchantPattern {
  /** Stable identifier (UUID generated by the caller). */
  readonly id: string;
  /** The field the pattern applies to (typically 'merchant'). */
  readonly fieldName: string;
  /** Human-readable description of the pattern. */
  readonly description: string;
  /** JavaScript-compatible regex source string (NOT compiled). */
  readonly regexSource: string;
  /** Regex flags. */
  readonly regexFlags: string;
  /** Number of corrections the pattern was learned from. */
  readonly sampleCount: number;
  /** Anonymized example patterns (NOT raw values). */
  readonly examplePatterns: readonly string[];
  /** ISO date-time when the pattern was learned. */
  readonly learnedAt: string;
}

// ---------------------------------------------------------------------------
// Learning
// ---------------------------------------------------------------------------

/**
 * Returns `true` when there are enough corrections to learn a pattern.
 *
 * The threshold is `MIN_CORRECTIONS_FOR_PATTERN` (10). Below that, the
 * learner returns `null` to avoid overfitting to noise.
 */
export function hasEnoughSamples(
  patterns: readonly CorrectionPatternCount[],
): boolean {
  const total = patterns.reduce((sum, p) => sum + p.count, 0);
  return total >= MIN_CORRECTIONS_FOR_PATTERN;
}

/**
 * Learns a merchant pattern from a list of anonymized correction patterns.
 *
 * Returns `null` when:
 *   - Fewer than `MIN_CORRECTIONS_FOR_PATTERN` (10) total corrections.
 *   - All corrections have the same extracted/corrected pattern (no
 *     variation to learn from).
 *   - The patterns don't yield a usable regex.
 *
 * CRITICAL: the returned pattern is an ANONYMIZED regex template — it
 * captures the SHAPE of merchant names (length, character classes) but
 * never the actual merchant name. The template can be applied to future
 * extractions to detect similar OCR errors.
 */
export function learnMerchantPattern(
  patterns: readonly CorrectionPatternCount[],
  learnedAt: string,
  patternId: string,
): LearnedMerchantPattern | null {
  if (patterns.length === 0) return null;
  if (!hasEnoughSamples(patterns)) return null;
  if (Number.isNaN(Date.parse(learnedAt))) return null;
  if (patternId.trim().length === 0) return null;

  // Aggregate by extracted→corrected pattern pair.
  const total = patterns.reduce((sum, p) => sum + p.count, 0);

  // Pick the most common extracted→corrected pair as the representative.
  const sorted = [...patterns].sort((a, b) => b.count - a.count);
  const mostCommon = sorted[0]!;
  if (mostCommon.count < MIN_CORRECTIONS_FOR_PATTERN) {
    // Even the most common single pattern is below threshold — try to
    // build a generalized pattern from the aggregate.
  }

  // Build a regex template from the most common pattern pair.
  // The template captures the SHAPE of the value (e.g. "starts with
  // uppercase letter, followed by 2-12 alphanumeric characters").
  const extractedShape = inferShape(mostCommon.extractedValuePattern);
  const correctedShape = inferShape(mostCommon.correctedValuePattern);

  if (extractedShape === null || correctedShape === null) {
    return null;
  }

  // Build a regex that matches values with the corrected shape.
  // The regex is a TEMPLATE — the caller compiles it with `new RegExp(...)`.
  const regexSource = correctedShape.regex;
  const regexFlags = 'i';

  // Description — describes what the pattern matches, without revealing
  // the actual merchant name.
  const description = `Merchant names that are ${correctedShape.description} (learned from ${total} corrections)`;

  // Examples — anonymized pattern strings, NOT raw values.
  const examplePatterns = sorted
    .slice(0, 5)
    .map((p) => `${p.extractedValuePattern} → ${p.correctedValuePattern}`);

  return Object.freeze({
    id: patternId,
    fieldName: mostCommon.fieldName,
    description,
    regexSource,
    regexFlags,
    sampleCount: total,
    examplePatterns: Object.freeze(examplePatterns),
    learnedAt,
  });
}

// ---------------------------------------------------------------------------
// Shape inference
// ---------------------------------------------------------------------------

interface ValueShape {
  readonly regex: string;
  readonly description: string;
}

/**
 * Infers the SHAPE of an anonymized value pattern and produces a regex
 * template that matches values of that shape.
 *
 * The shape captures:
 *   - Length category (short/medium/long)
 *   - Character classes (uppercase, lowercase, digits, special chars)
 *
 * Returns `null` when the shape cannot be inferred.
 */
function inferShape(anonymizedPattern: string): ValueShape | null {
  // Merchant patterns look like '<merchant:len=short,has_digits,has_special>'.
  // Parse the features out.
  const merchantMatch = anonymizedPattern.match(
    /^<merchant:([^>]+)>$/,
  );
  if (merchantMatch) {
    const features = merchantMatch[1]!.split(',');
    const lengthFeature = features.find((f) => f.startsWith('len='));
    const hasDigits = features.includes('has_digits');
    const hasSpecial = features.includes('has_special');

    let lengthRegex: string;
    let lengthDesc: string;
    switch (lengthFeature) {
      case 'len=short':
        lengthRegex = '{1,8}';
        lengthDesc = 'short (1-8 chars)';
        break;
      case 'len=medium':
        lengthRegex = '{9,24}';
        lengthDesc = 'medium (9-24 chars)';
        break;
      case 'len=long':
        lengthRegex = '{25,}';
        lengthDesc = 'long (25+ chars)';
        break;
      default:
        lengthRegex = '+';
        lengthDesc = 'any length';
    }

    // Build a character class based on features.
    const classes: string[] = ['A-Z', 'a-z'];
    if (hasDigits) classes.push('0-9');
    if (hasSpecial) classes.push("\\-'.&");
    const charClass = `[${classes.join('')}]`;

    return {
      regex: `^${charClass}${lengthRegex}$`,
      description: `${lengthDesc}, includes ${hasDigits ? 'digits, ' : ''}${hasSpecial ? 'special chars, ' : ''}letters`,
    };
  }

  // Date patterns look like '<date:YYYY-MM-DD>' etc.
  const dateMatch = anonymizedPattern.match(/^<date:([^>]+)>$/);
  if (dateMatch) {
    const format = dateMatch[1]!;
    switch (format) {
      case 'YYYY-MM-DD':
        return {
          regex: '^\\d{4}-\\d{2}-\\d{2}$',
          description: 'ISO date (YYYY-MM-DD)',
        };
      case 'YYYY-MM':
        return {
          regex: '^\\d{4}-\\d{2}$',
          description: 'ISO year-month (YYYY-MM)',
        };
      case 'YYYY':
        return {
          regex: '^\\d{4}$',
          description: '4-digit year',
        };
      case 'DD/MM/YYYY':
      case 'MM/DD/YYYY':
        return {
          regex: '^\\d{1,2}[/-]\\d{1,2}[/-]\\d{2,4}$',
          description: 'slash-or-dash-separated date',
        };
      default:
        return {
          regex: '^.*$',
          description: 'unknown date format',
        };
    }
  }

  // Amount patterns look like '<amount>' or '<non_amount>'.
  if (anonymizedPattern === '<amount>') {
    return {
      regex: '^[-+]?\\s*(?:₹|Rs\\.?|INR|USD|\\$|EUR|€|GBP|£)?\\s*\\d{1,12}(?:[.,]\\d{1,4})?\\s*$',
      description: 'amount with optional currency prefix',
    };
  }

  // Payment method patterns look like '<payment_method:card>' etc.
  const paymentMatch = anonymizedPattern.match(/^<payment_method:([^>]+)>$/);
  if (paymentMatch) {
    return {
      regex: '^(?i).*(?:card|credit|debit|cash|upi|wallet|paytm|phonepe|gpay).*$',
      description: `payment method (${paymentMatch[1]})`,
    };
  }

  // Generic placeholder — return null to signal "no shape".
  return null;
}

// ---------------------------------------------------------------------------
// Pattern application
// ---------------------------------------------------------------------------

/**
 * Returns `true` when the given value matches the learned pattern.
 *
 * Used by the OCR improvement pipeline to flag extractions that look
 * suspiciously different from the learned pattern.
 */
export function matchesLearnedPattern(
  pattern: LearnedMerchantPattern,
  value: string,
): boolean {
  try {
    const regex = new RegExp(pattern.regexSource, pattern.regexFlags);
    return regex.test(value);
  } catch {
    // Invalid regex — fail safe (don't match).
    return false;
  }
}

// ---------------------------------------------------------------------------
// Verification helper
// ---------------------------------------------------------------------------

/**
 * Returns `true` when the learned pattern contains a raw merchant name
 * (rather than an anonymized template). Used by tests as a defensive
 * assertion — should always return `false`.
 */
export function patternContainsRawMerchantName(
  pattern: LearnedMerchantPattern,
): boolean {
  // A raw merchant name would be a long string of mixed letters that
  // isn't wrapped in '<...>' and isn't a regex character class.
  const suspiciousPatterns = [
    // Common merchant-name patterns (raw).
    /\b(?:restaurant|cafe|hotel|store|mart|bazaar|kirana|swiggy|zomato|amazon|flipkart)\b/i,
  ];
  for (const re of suspiciousPatterns) {
    if (re.test(pattern.description)) return true;
    if (re.test(pattern.regexSource)) return true;
    for (const ex of pattern.examplePatterns) {
      if (re.test(ex)) return true;
    }
  }
  return false;
}
