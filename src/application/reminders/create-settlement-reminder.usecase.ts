
import {
  asReminderId,
  createSettlementReminder,
  type ReminderPrivacyMode,
  type ReminderType,
  type SettlementReminder,
} from '@domain/entities/settlement-reminder';
import { InvalidEntityError } from '@domain/errors';
import type { AuditRepository } from '@domain/repositories/audit.repository';
import type { SettlementReminderRepository } from '@domain/repositories/settlement-reminder.repository';
import { isWithinCoolDown, DEFAULT_COOL_DOWN_HOURS } from '@domain/services/reminders/reminder-scheduling-rules';
import type { DateTime } from '@domain/value-objects';
import { nowDateTime } from '@domain/value-objects';
import type { GroupId, MemberId, SettlementId, UserId } from '@shared-types/index';

/**
 * Use case: Create a settlement reminder.
 *
 * Phase 6 Track 6 / Prompt 59 — schedules a respectful payment
 * follow-up reminder. Enforces the cool-down period: if a
 * scheduled-or-sent reminder for the same (group, payer, receiver,
 * currency) tuple exists within the cool-down window, the use case
 * throws `InvalidEntityError` with a clear message.
 *
 * ── Cool-down ──
 *
 * The default cool-down is 24 hours (DEFAULT_COOL_DOWN_HOURS). The
 * caller may override it via `coolDownHours`. The cool-down is
 * per-tuple: a reminder to payer A does not cool-down a reminder
 * to payer B.
 *
 * ── Privacy mode ──
 *
 * The privacy mode is frozen at scheduling time. Later changes to
 * user preferences do not retroactively alter already-sent
 * notifications. The default is `private` (lock-screen hides the
 * amount).
 *
 * ── Wording ──
 *
 * The notification message is generated by the notification system
 * using the neutral `buildNeutralReminderMessage` function from the
 * scheduling-rules module. The use case does NOT generate the
 * message — it schedules the reminder; the dispatcher generates the
 * message at send time.
 */
export class CreateSettlementReminderUseCase {
  constructor(
    private readonly reminders: SettlementReminderRepository,
    private readonly audit: AuditRepository,
  ) {}

  async execute(input: CreateSettlementReminderInput): Promise<CreateSettlementReminderOutput> {
    // ── Validate required fields ──
    if (input.payerMemberId === undefined && input.receiverMemberId === undefined) {
      throw new InvalidEntityError(
        'CreateSettlementReminder: at least one of payerMemberId or receiverMemberId is required',
      );
    }

    const now: DateTime = input.now ?? nowDateTime();

    // ── Cool-down check ──
    if (input.payerMemberId !== undefined && input.receiverMemberId !== undefined) {
      const last = await this.reminders.findMostRecentForCoolDown(
        input.groupId,
        input.payerMemberId,
        input.receiverMemberId,
        input.currencyCode,
      );
      const coolDownHours = input.coolDownHours ?? DEFAULT_COOL_DOWN_HOURS;
      if (
        last !== null &&
        isWithinCoolDown(now, input.scheduledAt, last.scheduledAt, coolDownHours)
      ) {
        throw new InvalidEntityError(
          `CreateSettlementReminder: a reminder for this (payer, receiver, currency) tuple was already scheduled at ${last.scheduledAt}. The cool-down period (${coolDownHours}h) has not elapsed.`,
        );
      }
    }

    // ── Create the entity ──
    const id = asReminderId(generateId());
    const reminder = createSettlementReminder({
      id,
      groupId: input.groupId,
      ...(input.settlementId !== undefined ? { settlementId: input.settlementId } : {}),
      ...(input.payerMemberId !== undefined ? { payerMemberId: input.payerMemberId } : {}),
      ...(input.receiverMemberId !== undefined ? { receiverMemberId: input.receiverMemberId } : {}),
      currencyCode: input.currencyCode,
      ...(input.amountMinor !== undefined ? { amountMinor: input.amountMinor } : {}),
      reminderType: input.reminderType,
      scheduledAt: input.scheduledAt,
      ...(input.privacyMode !== undefined ? { privacyMode: input.privacyMode } : {}),
      createdBy: input.createdBy,
      now,
    });

    // ── Persist + audit ──
    await this.reminders.save(reminder);
    await this.audit.append({
      id: generateId(),
      entityType: 'settlement_reminder',
      entityId: id,
      action: 'create',
      ...(input.actorId !== undefined ? { actorId: input.actorId } : {}),
      groupId: input.groupId,
      newVersion: 1,
      changeSummary: {
        reminderType: input.reminderType,
        scheduledAt: input.scheduledAt,
        privacyMode: reminder.privacyMode,
      },
    });

    return { reminder };
  }
}

export interface CreateSettlementReminderInput {
  readonly groupId: GroupId;
  readonly settlementId?: SettlementId;
  readonly payerMemberId?: MemberId;
  readonly receiverMemberId?: MemberId;
  readonly currencyCode: string;
  readonly amountMinor?: number;
  readonly reminderType: ReminderType;
  readonly scheduledAt: DateTime;
  readonly privacyMode?: ReminderPrivacyMode;
  readonly createdBy: UserId;
  readonly actorId?: UserId;
  readonly now?: DateTime;
  /** Override the default 24-hour cool-down. */
  readonly coolDownHours?: number;
}

export interface CreateSettlementReminderOutput {
  readonly reminder: SettlementReminder;
}

function generateId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}
