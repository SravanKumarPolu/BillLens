-- Creates the 21 tables required for Phase 1:
--   profiles, guest_identity_links, groups, group_members, group_invites,
--   expenses, expense_payers, expense_splits, receipts, receipt_items,
--   settlements, device_installations, sync_conflicts, audit_logs,
--   expense_drafts, capture_sources, extraction_results, payment_evidence,
--   receipt_privacy_preferences, duplicate_candidates, field_corrections
--
-- Design principles:
--   1. UUID primary keys generated by clients (offline-first).
--   2. Common columns on every synchronised entity: id, created_at,
--      updated_at, deleted_at, version, created_by, last_modified_by,
--      client_created_at, client_updated_at.
--   3. Soft-deletion via deleted_at; never hard-delete financial records.
--   4. Optimistic concurrency via version (positive integer, starts at 1).
--   5. Server-side validation via CHECK constraints where possible.
--   6. Cross-row financial invariants (e.g. sum of splits = expense total)
--      are enforced by application transactions + server validation
--      (see docs/database-schema.md "Cross-row invariants" section).
-- ============================================================================

