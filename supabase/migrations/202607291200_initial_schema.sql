-- ============================================================================
-- Updated_at triggers
-- ============================================================================
-- Auto-update updated_at on every row update (for tables that have it).
create or replace function billlens_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Apply the trigger to every synchronised table.
do $$
declare
  t text;
  tables text[] := array[
    'profiles', 'guest_identity_links', 'groups', 'group_members',
    'group_invites', 'expenses', 'expense_payers', 'expense_splits',
    'receipts', 'receipt_items', 'settlements', 'device_installations',
    'sync_conflicts', 'expense_drafts', 'capture_sources',
    'extraction_results', 'payment_evidence', 'receipt_privacy_preferences',
    'duplicate_candidates', 'field_corrections'
  ];
begin
  foreach t in array tables loop
    execute format(
      'drop trigger if exists set_updated_at on %I; create trigger set_updated_at before update on %I for each row execute function billlens_set_updated_at();',
      t, t
    );
  end loop;
end $$;

