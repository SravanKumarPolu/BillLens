-- 17. extraction_results
-- ============================================================================
-- DECISION: extracted_fields are stored as JSONB, NOT as separate rows.
-- Justification:
--   1. Draft-stage data is mutable — fields change as the user edits.
--      JSONB allows atomic updates without row-by-row CRUD.
--   2. The number of fields varies (some receipts have 3 items, others 50).
--      A separate-row-per-field design would require complex joins for
--      every draft load.
--   3. Confirmed financial data (Expense, ExpenseSplit, etc.) IS stored
--      relationally — the JSONB approach applies ONLY to the draft stage.
--   4. Querying by individual field values is NOT needed during the draft
--      stage (the UI loads the entire draft at once).
--   5. Once confirmed, the draft's data is migrated to relational tables
--      (expenses, expense_payers, expense_splits) and the draft is marked
--      'confirmed' — the JSONB is retained for audit but not queried.
create table if not exists extraction_results (
  id                  uuid primary key,
  capture_source_id   uuid not null references capture_sources (id) on delete cascade,
  -- All extracted fields stored as JSONB (see decision justification above)
  extracted_data      jsonb not null,
  overall_confidence  real not null check (overall_confidence between 0 and 1),
  total_matches       boolean not null,
  raw_text            text,
  extracted_at        timestamptz not null,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  deleted_at          timestamptz,
  version             integer not null default 1 check (version > 0),
  client_created_at   timestamptz not null,
  client_updated_at   timestamptz not null
);

create index if not exists idx_extraction_results_capture on extraction_results (capture_source_id);
create index if not exists idx_extraction_results_active on extraction_results (id) where deleted_at is null;
create index if not exists idx_extraction_results_updated_at on extraction_results (updated_at);

